"""Build every Beretta UML figure: svg/*.svg, png/*.png (via headless Edge or Chrome) and index.html.

    py docs/diagrams/build.py            # SVG + index
    py docs/diagrams/build.py --png      # also PNG at 2x, for the Word report
    py docs/diagrams/build.py S1 B3      # only these figures
    py docs/diagrams/build.py --png --report   # caption-free copies in report/ for the capstone report

Standard library only. PNG export needs Microsoft Edge or Google Chrome installed.
"""
import os
import shutil
import subprocess
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
REPORT = "--report" in sys.argv     # no caption line, for documents that caption the figure themselves
if REPORT:
    os.environ["BERETTA_NO_CAPTION"] = "1"

import behavioural  # noqa: E402
import structural  # noqa: E402

SVG_DIR, PNG_DIR = ((os.path.join(HERE, "report", "svg"), os.path.join(HERE, "report", "png")) if REPORT
                    else (os.path.join(HERE, "svg"), os.path.join(HERE, "png")))
GROUPS = [("Structural diagrams", structural.FIGURES), ("Behavioural diagrams", behavioural.FIGURES)]
BROWSERS = [r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Google\Chrome\Application\chrome.exe",
            "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "google-chrome", "chromium"]


def browser():
    for b in BROWSERS:
        if os.path.isfile(b) or shutil.which(b):
            return b
    return None


def to_png(exe, svg_path, png_path, w, h):
    html = os.path.join(PNG_DIR, "_frame.html")
    with open(html, "w", encoding="utf-8") as fh:
        fh.write(f'<!doctype html><html><body style="margin:0;background:#fff">'
                 f'<img src="file:///{svg_path.replace(os.sep, "/")}" width="{w}" height="{h}"></body></html>')
    subprocess.run([exe, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=2",
                    f"--window-size={w},{h}", f"--screenshot={png_path}", "file:///" + html.replace(os.sep, "/")],
                   check=True, capture_output=True, timeout=60)


def index(built):
    cards = []
    for group, figs in GROUPS:
        cards.append(f"<h2>{escape(group)}</h2>")
        for num, slug, title, _ in figs:
            if slug not in built:
                continue
            cards.append(f'<section id="{num}"><h3>{num}. {escape(title)}</h3>'
                         f'<a href="svg/{slug}.svg"><img src="svg/{slug}.svg" alt="{escape(title)}" loading="lazy"></a>'
                         f'</section>')
    toc = "".join(f'<a href="#{n}">{n} {escape(t)}</a>' for _, figs in GROUPS for n, s, t, _ in figs if s in built)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Beretta UML diagrams</title>
<style>
:root {{ --ground:#f2f4f7; --surface:#fff; --border:#e1e5eb; --text:#0b0e14; --muted:#555d6b; --data:#1d5fbf; }}
body {{ margin:0; background:var(--ground); color:var(--text); font:14px/1.5 "Segoe UI",Helvetica,Arial,sans-serif; }}
header {{ padding:24px 32px 8px; }} h1 {{ margin:0 0 4px; font-size:22px; }} p {{ margin:0; color:var(--muted); }}
nav {{ display:flex; flex-wrap:wrap; gap:6px; padding:12px 32px; }}
nav a {{ background:var(--surface); border:1px solid var(--border); border-radius:4px; padding:3px 9px;
        color:var(--text); text-decoration:none; font-size:12.5px; }}
nav a:hover {{ border-color:var(--data); color:var(--data); }}
main {{ padding:0 32px 48px; }} h2 {{ font-size:17px; margin:28px 0 8px; }}
section {{ background:var(--surface); border:1px solid var(--border); border-radius:8px; padding:12px 16px;
          margin:0 0 16px; }}
h3 {{ margin:0 0 8px; font-size:14px; }} img {{ width:100%; height:auto; display:block; }}
</style></head><body>
<header><h1>Beretta UML diagrams</h1><p>Generated by docs/diagrams/build.py from the code. Click a figure to open the SVG.</p></header>
<nav>{toc}</nav><main>{"".join(cards)}</main></body></html>
"""


def main(argv):
    want = {a.upper() for a in argv if not a.startswith("--")}
    png = "--png" in argv
    os.makedirs(SVG_DIR, exist_ok=True)
    exe = browser() if png else None
    if png:
        os.makedirs(PNG_DIR, exist_ok=True)
        if not exe:
            print("No Edge or Chrome found; skipping PNG export.")
    built = set()
    for _, figs in GROUPS:
        for num, slug, title, fn in figs:
            built.add(slug)
            if want and num.upper() not in want:
                continue
            d = fn()
            path = os.path.join(SVG_DIR, slug + ".svg")
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(d.svg())
            line = f"{num:4} {slug}.svg"
            if exe:
                to_png(exe, path, os.path.join(PNG_DIR, f"{num}_{slug}.png"), d.w, d.h)
                line += f"  + png/{num}_{slug}.png"
            print(line)
    if exe and os.path.exists(os.path.join(PNG_DIR, "_frame.html")):
        os.remove(os.path.join(PNG_DIR, "_frame.html"))
    if REPORT:
        return
    with open(os.path.join(HERE, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(index(built))
    print("index.html")


if __name__ == "__main__":
    main(sys.argv[1:])
