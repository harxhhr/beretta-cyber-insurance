def write_vm_kit(kit, ca_file, server, token):
    """Everything the VM needs, in one folder (share it with the VM, or copy vm-kit.zip across)."""
    os.makedirs(kit, exist_ok=True)
    for name in os.listdir(kit):                       # empty it but keep the folder (it may be a shared folder)
        path = os.path.join(kit, name)
        shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
    agent_src = os.path.join(ROOT, "kyh-agent", "agent")
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    shutil.copytree(os.path.join(agent_src, "kyh_agent"), os.path.join(kit, "agent", "kyh_agent"), ignore=ignore)
    shutil.copytree(os.path.join(agent_src, "install", "windows"), os.path.join(kit, "agent", "install", "windows"))
    shutil.copy(ca_file, os.path.join(kit, "ca.pem"))
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    # PowerShell 5.1 reads BOM-less files as ANSI; keep the scripts ASCII and CRLF.
    for name, text in (("connect-vm.ps1", CONNECT_PS1.format(server=server, token=token, generated=stamp)),
                       ("kyh-vm-demo.ps1", DEMO_PS1)):
        with open(os.path.join(kit, name), "w", encoding="ascii", newline="\r\n") as fh:
            fh.write(text)
    with open(os.path.join(kit, "README.txt"), "w", encoding="ascii", newline="\r\n") as fh:
        fh.write(f"Beretta VM kit, generated {stamp}\n\nCollector: {server}\nEnrollment token: {token}\n\n"
                 "In the VM, elevated PowerShell, inside this folder:\n"
                 "  powershell -ExecutionPolicy Bypass -File .\\connect-vm.ps1\n"
                 "  powershell -ExecutionPolicy Bypass -File .\\kyh-vm-demo.ps1 make-green\n"
                 "  powershell -ExecutionPolicy Bypass -File .\\kyh-vm-demo.ps1 firewall-off\n")
    zpath = os.path.join(os.path.dirname(kit), "vm-kit.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(kit):
            for f in files:
                full = os.path.join(root, f)
                z.write(full, os.path.join("vm-kit", os.path.relpath(full, kit)))
    return zpath


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(ROOT, "demo-linked"))
    ap.add_argument("--platform-port", type=int, default=8000)
    ap.add_argument("--collector-port", type=int, default=8443)
    ap.add_argument("--no-input", action="store_true", help="start everything and wait (for screen recording)")
    ap.add_argument("--vm-ip", default=None, help="laptop's VirtualBox host-only IP, e.g. 192.168.56.1: "
                                                  "serve the collector there over HTTPS for a real VM agent")
    ap.add_argument("--vm-endpoints", type=int, default=1, help="real VMs you will connect (default 1)")
    ap.add_argument("--kit", default=os.path.join(ROOT, "vm-kit"), help="where to write the VM kit")
    a = ap.parse_args()
    tls = ensure_tls(os.path.join(ROOT, "demo-tls"), a.vm_ip) if a.vm_ip else None
    declared = len(HOSTS) + (a.vm_endpoints if a.vm_ip else 0)

    shutil.rmtree(a.data, ignore_errors=True)
    os.makedirs(os.path.join(a.data, "platform"))
    os.environ["KYH_DB"] = os.path.join(a.data, "platform", "kyh.db")
    os.environ["KYH_SECRETS"] = os.path.join(a.data, "platform", "secrets.json")
    sys.path[:0] = [os.path.join(ROOT, "kyh-cyber-insurance"), os.path.join(ROOT, "kyh-agent", "agent"),
                    os.path.join(ROOT, "kyh-agent", "collector")]
    from app import database as pdb
    from app.api import make_server as make_platform
    from kyh_agent import config as agent_config, policy as agent_policy
    from kyh_agent.agent import Agent, enroll
    from kyh_agent.security import build_hash
    from kyh_agent.simulate import registry_for
    from kyh_collector import core, platform_link
    from kyh_collector.server import make_server as make_collector

    # ---------------------------------------------------------------- Part 1: Beretta platform
    platform = make_platform("127.0.0.1", a.platform_port)
    threading.Thread(target=platform.serve_forever, daemon=True).start()
    purl = f"http://127.0.0.1:{a.platform_port}"
    with open(os.environ["KYH_SECRETS"]) as fh:
        tok = json.load(fh)["role_tokens"]
    admin, uw = {"X-Auth-Token": tok["admin"]}, {"X-Auth-Token": tok["underwriter"]}
    with open(os.path.join(a.data, "platform", "demo_profiles.json")) as fh:
        b = json.load(fh)["B"]

    curl = f"https://{a.vm_ip}:{a.collector_port}" if a.vm_ip else f"http://127.0.0.1:{a.collector_port}"
    st, reg = http("POST", purl + "/api/admin/collectors", {"name": "Beretta collector", "dashboard_url": curl}, admin)
    http("POST", f"{purl}/api/admin/collectors/{reg['collector_id']}/links",
         {"company_id": b["company_id"], "collector_company_id": "co_kalinga"}, admin)

    # ---------------------------------------------------------------- Part 2: collector, linked
    cdata = os.path.join(a.data, "collector")
    os.makedirs(cdata)
    with open(os.path.join(cdata, "settings.json"), "w") as fh:
        json.dump({"push_interval_seconds": 5, "coverage_onboarding_days": 0}, fh)
    platform_link.save_link(cdata, purl, reg["collector_id"], reg["secret"], dashboard_url=curl)
    if tls:   # listen on the host-only adapter only: reachable from the VM, not from Wi-Fi
        collector = make_collector(cdata, a.vm_ip, a.collector_port, tls["cert"], tls["key"])
    else:
        collector = make_collector(cdata, "127.0.0.1", a.collector_port)
    threading.Thread(target=collector.serve_forever, daemon=True).start()
    capp = collector.app
    conn = capp.conn()
    now = capp.clock()
    ctoken = core.create_admin_token(conn, now)
    core.add_company(conn, now, "Kalinga Components Ltd", declared, "Manufacturing", True, "co_kalinga")
    enr = core.issue_enrollment_token(conn, now, "co_kalinga", 20, 30)
    core.approve(conn, now, "approved_builds", build_hash(), "kyh-agent 2.0.0")
    core.approve(conn, now, "approved_policies", agent_policy.load().hash, "baseline 2.1.0")
    conn.close()

    # ---------------------------------------------------------------- four simulated endpoints
    pol = agent_policy.load()
    agents, lock = {}, threading.Lock()
    for h, os_name in HOSTS.items():
        state = os.path.join(a.data, "agents", h)
        cfg = agent_config.load(os.path.join(state, "config.json"))
        enroll(cfg, curl, enr, tls["ca"] if tls else None, pol, hostname=h)
        cfg["os_override"] = os_name
        agents[h] = Agent(cfg, pol, state, simulate="healthy", platform="windows")

    def push(h, profile=None):
        ag = agents[h]
        with lock:
            if profile:
                ag.simulate = profile
                ag.runner.registry = registry_for(profile, ag.platform)
            ag.scan(force_full=True)
            ag.flush()

    for h in HOSTS:
        push(h)
    conn = capp.conn()   # link only once every endpoint has reported, so the first roll-up is complete
    platform_link.link_company(conn, capp.clock(), "co_kalinga", b["company_id"])
    conn.close()
    capp.worker.wake.set()

    def heartbeats():
        while True:
            time.sleep(30)
            for ag in agents.values():
                with lock:
                    ag.enqueue("heartbeat", [])
                    ag.flush()

    threading.Thread(target=heartbeats, daemon=True).start()

    print("\n" + "=" * 78)
    print(f"Beretta platform (Part 1): {purl}/#/companies/{b['company_id']}/monitoring")
    print(f"Collector    (Part 2): {curl}   admin token: {ctoken}")
    print("Kalinga Components is linked on both sides; 4 simulated endpoints are reporting.")
    print("=" * 78)
    with open(os.path.join(a.data, "demo.json"), "w") as fh:
        json.dump({"platform": purl, "collector": curl, "collector_token": ctoken, "company_id": b["company_id"],
                   "policy_id": b["policy_id"]}, fh)

    zpath = write_vm_kit(a.kit, tls["ca"], curl, enr) if tls else None

    def vm_steps():
        print(f"VM kit: {a.kit}   (also zipped: {zpath})")
        print(f"  Collector for the VM: {curl}    enrollment token: {enr}")
        print("  In the VM (elevated PowerShell, inside the shared vm-kit folder):")
        print("    powershell -ExecutionPolicy Bypass -File .\\connect-vm.ps1")
        print("  Bind only after the VM shows up here (type: hosts), or coverage starts below 90%.")

    if tls:
        print(f"Declared endpoints: {declared} ({len(HOSTS)} simulated + {a.vm_endpoints} real VM)")
        vm_steps()
        print("=" * 78)

    def hosts():
        from kyh_collector import evaluate as cev
        c = capp.conn()
        try:
            snap = cev.evaluate_company(c, "co_kalinga", capp.clock(), capp.settings, persist=False)
        finally:
            c.close()
        for h in snap.get("hosts", []):
            bad = [k for k, v in h["controls"].items() if v["status"] == "FAIL"]
            kind = "simulated" if h["simulated"] else "REAL"
            print(f"  {h['hostname'] or h['agent_id']:<18} {kind:<10} {h['liveness']['state']:<11} "
                  f"last seen {str(h['last_seen'])[:19]}  " + (f"FAIL: {', '.join(bad)}" if bad else "all OK"))
        print(f"  reporting {len(snap.get('hosts', []))} of {declared} declared endpoints")

    def vm_not_ready():
        """Real hosts that are missing or fail PATCH / EDR / BACKUP (the platform's endpoint warranties)."""
        from kyh_collector import evaluate as cev
        c = capp.conn()
        try:
            snap = cev.evaluate_company(c, "co_kalinga", capp.clock(), capp.settings, persist=False)
        finally:
            c.close()
        real = [h for h in snap.get("hosts", []) if not h["simulated"]]
        out = [] if len(real) >= a.vm_endpoints else [f"only {len(real)} of {a.vm_endpoints} VM(s) reporting"]
        for h in real:
            for ctl in ("PATCH", "EDR", "BACKUP"):
                cell = h["controls"].get(ctl, {})
                if cell.get("status") == "FAIL":
                    out.append(f"{h['hostname']}: {ctl} FAIL - {cell.get('reason', '')[:90]}")
        return out

    def status():
        st, w = http("GET", f"{purl}/api/policies/{b['policy_id']}/warranties", headers=uw)
        st, p = http("GET", f"{purl}/api/policies/{b['policy_id']}", headers=uw)
        print(f"  policy {p['policy']['status']}  premium {p['policy']['bound_premium']}")
        for x in w.get("warranties", []):
            print(f"  {x['control_name']:<34} {x['state']}")

    if a.no_input:
        while True:
            time.sleep(3600)
    print(__doc__.split("Commands at the kyh> prompt:", 1)[1])
    while True:
        try:
            cmd = input("kyh> ").strip().split()
        except (EOFError, KeyboardInterrupt):
            break
        if not cmd:
            continue
        if cmd[0] == "quit":
            break
        elif cmd[0] == "bind":
            if tls and cmd[-1] != "--force":
                not_ready = vm_not_ready()
                if not_ready:
                    print("  Not binding yet: a real VM fails a warranty check, so that warranty would start IN_GRACE.")
                    for line in not_ready:
                        print("   ", line)
                    print("  Fix it in the VM (kyh-vm-demo.ps1 make-green), or type 'bind --force' to bind anyway.")
                    continue
            st, q = http("POST", purl + "/api/quote", {"policy_id": b["policy_id"]}, uw)
            st, r = http("POST", purl + "/api/policies/bind", {"policy_id": b["policy_id"],
                                                              "calculation_id": q.get("calculation_id")}, uw)
            print(f"  bound at INR {r.get('bound_premium')}" if st == 200 else f"  {r}")
        elif cmd[0] == "break" and len(cmd) == 3 and cmd[1] in agents:
            push(cmd[1], cmd[2])
            print(f"  {cmd[1]} now reports '{cmd[2]}'; the platform hears about it within ~5 s")
        elif cmd[0] == "fix" and len(cmd) == 2 and cmd[1] in agents:
            push(cmd[1], "healthy")
            print(f"  {cmd[1]} healthy again")
        elif cmd[0] == "fast-forward":
            c = pdb.connect()
            n = c.execute("UPDATE warranties SET grace_expires_at=? WHERE state='IN_GRACE'",
                          (pdb.now_iso(),)).rowcount
            from app import audit
            audit.log(c, "demo", "DEMO_TIME_TRAVEL", "SYSTEM", "warranties",
                      new_value={"note": "grace periods ended early for a demonstration", "count": n})
            c.commit()
            print(f"  {n} grace period(s) ended. Refresh the platform page.")
        elif cmd[0] == "status":
            status()
        elif cmd[0] == "hosts":
            hosts()
        elif cmd[0] == "vm":
            vm_steps() if tls else print("  start with --vm-ip <host-only IP> to connect a real VM")
        else:
            print("  commands: bind | break <host> <profile> | fix <host> | fast-forward | status | hosts | vm | quit")
    collector.shutdown()
