"""Linked demo: Beretta platform (Part 1) + live-monitoring collector (Part 2) + 4 simulated endpoints.

    python run_linked_demo.py                          everything on this laptop (4 simulated endpoints)
    python run_linked_demo.py --vm-ip 192.168.56.1     + a real Windows VM that reports over HTTPS

With --vm-ip the collector listens on that address only (the laptop's VirtualBox host-only IP) with a
private-CA TLS certificate, the company declares one more endpoint, and a ready-to-run kit for the VM is
written to vm-kit/ (agent, ca.pem, connect-vm.ps1, kyh-vm-demo.ps1). Share that folder with the VM.

Opens two dashboards:
    Beretta platform http://127.0.0.1:8000   (pricing, binding, the warranty state machine)
    Collector      http://127.0.0.1:8443   (endpoints, evidence; paste the admin token it prints)

Commands at the kyh> prompt:
    bind                      quote and bind Kalinga Components on the platform (same as the UI button);
                              with a VM it first checks the VM passes PATCH, EDR and BACKUP ('bind --force' skips)
    break <host> <profile>    e.g. break KAL-PLANT-WS03 edr_down
                              profiles: edr_down, edr_stale, patch_overdue, backup_stale, mixed
    fix <host>                host back to healthy
    fast-forward              DEMO ONLY: end every running grace period now (shows BREACHED)
    status                    warranty states on the platform
    hosts                     every endpoint the collector knows, with liveness and failing checks
    vm                        print the VM connection steps again
    quit
Endpoint data is SIMULATED and labelled as such everywhere.
"""

