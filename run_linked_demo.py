def http(method, url, body=None, headers=None):
    req = urllib.request.Request(url, method=method, data=json.dumps(body).encode() if body is not None else None,
                                 headers={"Content-Type": "application/json", **(headers or {})})
    try:
        with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(req, timeout=10) as r:
            return r.status, json.loads(r.read())
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


def ensure_tls(tls_dir, ip):
    """Private CA + server certificate for the VM link. Kept across runs so the VM and browser keep trusting it."""
    sys.path.insert(0, os.path.join(ROOT, "kyh-agent", "collector"))
    from kyh_collector.__main__ import gen_cert
    hosts = [ip, "127.0.0.1", "localhost"]
    want = {"hosts": hosts, "format": 2}   # format 2: key identifiers that Python 3.13+ requires
    meta = os.path.join(tls_dir, "hosts.json")
    paths = {k: os.path.join(tls_dir, v) for k, v in {"ca": "ca.pem", "cert": "server.pem", "key": "server.key"}.items()}
    try:
        with open(meta) as fh:
            same = json.load(fh) == want
    except (OSError, ValueError):
        same = False
    if not (same and all(os.path.exists(x) for x in paths.values())):
        shutil.rmtree(tls_dir, ignore_errors=True)
        gen_cert(tls_dir, hosts)
        with open(meta, "w") as fh:
            json.dump(want, fh)
        print(f"Created a private CA and certificate for {ip} in {tls_dir}")
    return paths


